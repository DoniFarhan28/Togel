export function getInitialDraws(marketId: string): DrawRecord[] {
  let rawList: Array<{ date: string; day?: string; period: string; number: string }> = [];
  if (marketId === 'sydney') rawList = RAW_SYDNEY_DATA;
  else if (marketId === 'hongkong') rawList = RAW_HONGKONG_DATA;
  else if (marketId === 'macau') rawList = RAW_MACAU_DATA;
  else if (marketId === 'singapore') rawList = RAW_SINGAPORE_DATA;

  return rawList.map((item, idx) => ({
    id: `${marketId}-${item.period}-${idx}`,
    marketId,
    date: item.date,
    day: item.day,
    period: item.period,
    number: item.number,
    createdAt: Date.now() - (rawList.length - idx) * 3600000
  }));
}
